export type TipoCuenta = "activo" | "pasivo" | "patrimonio" | "ingreso" | "costo" | "gasto";

export const TIPO_POR_CLASE: Record<string, TipoCuenta> = {
  "1": "activo",
  "2": "pasivo",
  "3": "patrimonio",
  "4": "ingreso",
  "5": "costo",
  "6": "gasto",
};

// Activos, costos y gastos crecen por el debe; pasivos, patrimonio e ingresos por el haber.
export function esDeudora(tipo: TipoCuenta): boolean {
  return tipo === "activo" || tipo === "costo" || tipo === "gasto";
}

export function nivelDeCodigo(codigo: string): number {
  if (codigo.length <= 2) return codigo.length;
  return Math.min(6, Math.ceil(codigo.length / 2) + 1);
}
